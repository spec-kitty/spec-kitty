@dataclass(frozen=True)
class SynthesisResult:
    """Per-target result assembled by the synthesis pipeline.

    Fields are populated by WP02 (synthesize_pipeline.py). WP01 defines the
    type so downstream WPs share a common output contract.
    """

    target_kind: str
    target_slug: str
    adapter_output: AdapterOutput
    """Raw adapter output; orchestration validates and writes it."""

    inputs_hash: str
    """Full SHA-256 hex digest of the normalized SynthesisRequest."""

    effective_adapter_id: str
    """adapter_id_override if set; else adapter.id."""

    effective_adapter_version: str
    """adapter_version_override if set; else adapter.version."""

    reconciliation: ReconciliationDelta | None = None
    """Preserve/prune/dry-run delta from reconciling this run's overlay +
    manifest against on-disk state (WP01, FR-009). ``synthesize()`` always
    populates this; ``None`` only guards construction sites that predate the
    reconciliation seam (``resynthesize()`` does not reconcile — it runs its
    own bounded merge — and leaves this at the default)."""

    reference_warnings: tuple[str, ...] = ()
    """Unresolved project-profile reference warnings from this run's overlay
    emission (#4121, MAJOR 2) — the same strings ``emit_project_layer`` logs.
    Carried on the result so CLI callers can surface them instead of them
    living only in ``logging`` output. Empty when nothing was re-emitted or
    every reference resolved."""


def _built_in_drg_from_snapshot(snapshot: object) -> object:
    """Normalize a request DRG snapshot into a validate-able DRGGraph payload."""
    if not isinstance(snapshot, dict):
        return snapshot

    normalized = dict(snapshot)
    normalized.setdefault("nodes", [])
    normalized.setdefault("edges", [])
    normalized["schema_version"] = "1.0"
    normalized.setdefault("generated_at", "1970-01-01T00:00:00+00:00")
    normalized.setdefault("generated_by", "request.drg_snapshot")
    return normalized


