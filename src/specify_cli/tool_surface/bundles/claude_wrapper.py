"""Runtime bootstrap wrapper scripts for the Claude Code plugin bundle (WP05).

Generates the ``bin/spec-kitty-wrapper`` (bash) and ``bin/spec-kitty-wrapper.cmd``
(Windows CMD) scripts that Claude Code invokes when executing a Spec Kitty skill.

Both wrappers implement the same runtime resolution:

1. If ``spec-kitty`` is on PATH **and** reports a version inside the bundle's
   supported series, delegate directly (fast path for users who have a
   compatible CLI installed).
2. Otherwise, if ``uvx`` is on PATH, run the pinned release with
   ``uvx --from "spec-kitty-cli=={VERSION}" spec-kitty``. ``uvx <requirement>``
   alone would run an executable named after the distribution, and the
   distribution ships ``spec-kitty``, not ``spec-kitty-cli`` (#6476).
3. If the pin cannot be resolved (a bundle built from an unpublished version),
   retry with the series range ``spec-kitty-cli>=VERSION,<NEXT_MINOR`` so the
   plugin still runs the newest published release of the line it was built for.
4. If neither works, print a remedy that matches the project's uv/pipx
   installation guidance and exit 1.

``__SPEC_KITTY_VERSION__`` is substituted with the real version string at build
time by :func:`write_wrappers`.  The wrapper files are generated artefacts and
are **not** committed to the source repository — they live only under the
caller-supplied ``bundle_dir``.

**Scope guard (FR-016, C-006):** This module only writes to the
``bin/`` subdirectory of the caller-supplied ``bundle_dir``.  It never installs,
registers, enables, or publishes the bundle.
"""

from __future__ import annotations

import re
import stat
from pathlib import Path


# Placeholder that is substituted at build time with the real package version.
_VERSION_PLACEHOLDER = "__SPEC_KITTY_VERSION__"

# The `<major>.<minor>` prefix of a version string — the release series a plugin
# bundle is built for. Anchored so `4.0.0rc8` yields `4.0` and `10.11.0.dev1`
# yields `10.11`, while a string that does not start with a version yields None.
_SERIES_PATTERN = re.compile(r"(?P<major>\d+)\.(?P<minor>\d+)")

# Template for the bash wrapper script.
_BASH_WRAPPER_TEMPLATE = """\
#!/usr/bin/env bash
# Spec Kitty runtime bootstrap — compatible CLI on PATH, else the pinned runtime.
# Generated by spec-kitty plugin build. Do not edit manually.
set -euo pipefail

VERSION="{version}"
SERIES="{series}"
PINNED_SPEC="{pinned_requirement}"
SERIES_SPEC="{range_requirement}"

# Fast path: a CLI inside the bundle's supported series. The version probe also
# proves the binary is reachable (#497); an unparseable answer is not a match.
if command -v spec-kitty >/dev/null 2>&1; then
    installed="$(spec-kitty --version 2>/dev/null || true)"
    installed_series="$(printf '%s\\n' "$installed" | awk 'match($0, /[0-9]+\\.[0-9]+/) {{ print substr($0, RSTART, RLENGTH); exit }}')"
    if [ -n "$installed_series" ] && [ "$installed_series" = "$SERIES" ]; then
        exec spec-kitty "$@"
    fi
fi

# Fallback: the pinned requirement, then the bundle's series if that pin is not
# published. A requirement that resolves is used; a CLI that fails to run is not
# retried against another version.
if command -v uvx >/dev/null 2>&1; then
    for from_spec in "$PINNED_SPEC" "$SERIES_SPEC"; do
        [ -n "$from_spec" ] || continue
        if uvx --from "$from_spec" spec-kitty --version >/dev/null 2>&1; then
            exec uvx --from "$from_spec" spec-kitty "$@"
        fi
    done
fi

echo "Error: no usable spec-kitty found (expected the $SERIES release series)." >&2
echo "Install it with 'uv tool install spec-kitty-cli' or 'pipx install spec-kitty-cli'," >&2
echo "or install 'uvx' so the plugin can run the pinned version on demand." >&2
exit 1
"""

# Template for the Windows CMD wrapper script.
#
# EXIT /B %ERRORLEVEL% must never sit inside a parenthesized IF block: cmd.exe
# expands %VAR% in a compound statement at parse time, so it would capture the
# errorlevel left by the preceding `where` probe (always 0 on the branch taken)
# rather than the errorlevel `spec-kitty`/`uvx` actually returned. GOTO keeps
# each EXIT /B outside any parentheses so the expansion happens at runtime.
#
# The series requirement names `>=' and `<' — both redirection operators in
# cmd.exe — so it is stored and used quoted.
_CMD_WRAPPER_TEMPLATE = """\
@echo off
REM Spec Kitty runtime bootstrap for Windows.
REM Generated by spec-kitty plugin build. Do not edit manually.
SET "VERSION={version}"
SET "SERIES={series}"
SET "PINNED_SPEC={pinned_requirement}"
SET "SERIES_SPEC={range_requirement}"

REM Fast path: a CLI inside the bundle's supported series.
where spec-kitty >nul 2>&1
IF ERRORLEVEL 1 GOTO try_pinned
SET "INSTALLED="
FOR /F "usebackq tokens=*" %%v IN (`spec-kitty --version 2^>nul`) DO IF NOT DEFINED INSTALLED SET "INSTALLED=%%v"
IF NOT DEFINED INSTALLED GOTO try_pinned
REM The version may be printed bare or after a program name, so accept either.
ECHO %INSTALLED%| findstr /C:" %SERIES%." >nul 2>&1
IF NOT ERRORLEVEL 1 GOTO path_cli_matches
ECHO %INSTALLED%| findstr /B /C:"%SERIES%." >nul 2>&1
IF ERRORLEVEL 1 GOTO try_pinned
:path_cli_matches
spec-kitty %*
EXIT /B %ERRORLEVEL%

REM Fallback: the pinned requirement, then the supported series.
:try_pinned
where uvx >nul 2>&1
IF ERRORLEVEL 1 GOTO no_runtime
uvx --from "%PINNED_SPEC%" spec-kitty --version >nul 2>&1
IF ERRORLEVEL 1 GOTO try_series
uvx --from "%PINNED_SPEC%" spec-kitty %*
EXIT /B %ERRORLEVEL%

:try_series
IF "%SERIES_SPEC%"=="" GOTO no_runtime
uvx --from "%SERIES_SPEC%" spec-kitty --version >nul 2>&1
IF ERRORLEVEL 1 GOTO no_runtime
uvx --from "%SERIES_SPEC%" spec-kitty %*
EXIT /B %ERRORLEVEL%

:no_runtime
echo Error: no usable spec-kitty found (expected the %SERIES% release series).
echo Install it with "uv tool install spec-kitty-cli" or "pipx install spec-kitty-cli",
echo or install "uvx" so the plugin can run the pinned version on demand.
EXIT /B 1
"""

# Owner-only rwx bits for a local executable file.
_EXECUTABLE_MODE = stat.S_IRUSR | stat.S_IWUSR | stat.S_IXUSR


def supported_series(version: str) -> str | None:
    """Return the ``<major>.<minor>`` release series of *version*.

    ``"4.0.0rc8"`` -> ``"4.0"``. Returns ``None`` when *version* does not start
    with a ``<major>.<minor>`` pair, so a caller never invents a series for a
    string it cannot read.
    """
    match = _SERIES_PATTERN.match(version.strip())
    if match is None:
        return None
    return f"{match.group('major')}.{match.group('minor')}"


def uvx_requirements(version: str) -> tuple[str, str]:
    """Return the ``uvx --from`` requirements for *version*.

    The first entry is the exact pin the bundle was built from; the second is
    the same release series (``>=VERSION,<NEXT_MINOR``) used when that exact
    version is not published. The second entry is ``""`` when *version* has no
    readable series.

    This is the single authority for "which CLI versions may this bundle run":
    the templates embed both requirements and the PATH gate compares against
    the same series.
    """
    pinned = f"spec-kitty-cli=={version}"
    series = supported_series(version)
    if series is None:
        return pinned, ""
    major, minor = series.split(".")
    return pinned, f"spec-kitty-cli>={version},<{major}.{int(minor) + 1}"


def _render(template: str, version: str) -> str:
    pinned, series_requirement = uvx_requirements(version)
    return template.format(
        version=version,
        series=supported_series(version) or "",
        pinned_requirement=pinned,
        range_requirement=series_requirement,
    )


def write_wrappers(
    bundle_dir: Path,
    version: str | None = None,
    *,
    prepared: tuple[Path, bytes, int] | None = None,
) -> None:
    """Write ``bin/spec-kitty-wrapper`` and ``bin/spec-kitty-wrapper.cmd``.

    Both files are generated under ``bundle_dir / "bin"`` with ``version``
    substituted for :data:`_VERSION_PLACEHOLDER`.  The bash script is made
    owner-executable (mode 700); Windows filesystem permissions are unchanged.

    Parameters
    ----------
    bundle_dir:
        Root of the plugin bundle (e.g. ``dist/spec-kitty-plugins/claude-code/``).
    version:
        The resolved package version string (e.g. ``"3.2.0"``).  Must be a
        non-empty string; the caller is responsible for validation.

    Raises
    ------
    ValueError
        When *version* is empty.
    """
    if prepared is not None:
        from .projection import observe_confined, write_staged_file

        path, content, mode = prepared
        if path not in {bundle_dir / "bin/spec-kitty-wrapper", bundle_dir / "bin/spec-kitty-wrapper.cmd"}:
            raise ValueError("Prepared wrapper destination is outside the wrapper layout")
        observe_confined(bundle_dir, path)
        write_staged_file(path, content, mode)
        return
    if not version:
        raise ValueError("version must be a non-empty string")

    from ..operations import ApplyConsent, AssessmentInputs
    from ._builder import finish_build
    from .model import StagedFile
    from .projection import confined_output, prepare_staging, staging_root

    root = staging_root(bundle_dir)
    directory = confined_output(bundle_dir, root)
    inputs = AssessmentInputs(root, consent=ApplyConsent(automatic=True))
    files = (
        StagedFile(
            (directory / "bin/spec-kitty-wrapper").relative_to(root.path).as_posix(), wrapper_bash_content(version).encode("utf-8"), _EXECUTABLE_MODE, wrapper=True
        ),
        StagedFile((directory / "bin/spec-kitty-wrapper.cmd").relative_to(root.path).as_posix(), wrapper_cmd_content(version).encode("utf-8"), wrapper=True),
    )
    finish_build(prepare_staging(inputs, files, ()))


def wrapper_bash_content(version: str) -> str:
    """Return the rendered bash wrapper content for *version*.

    Useful for inspection and testing without touching the filesystem.
    """
    return _render(_BASH_WRAPPER_TEMPLATE, version)


def wrapper_cmd_content(version: str) -> str:
    """Return the rendered Windows CMD wrapper content for *version*.

    Useful for inspection and testing without touching the filesystem.
    """
    return _render(_CMD_WRAPPER_TEMPLATE, version)


# Content helpers are consumed during preparation; write_wrappers also accepts
# one retained member during guarded batch application without rendering again.
__all__ = [
    "write_wrappers",
]
