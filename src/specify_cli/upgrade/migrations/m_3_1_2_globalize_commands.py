"""Migration 3.1.2: Safely remove project-level spec-kitty command files.

As of 3.1.2, slash commands (``spec-kitty.*.md``, ``spec-kitty.*.toml``, etc.)
are installed globally to the user's home agent directories
(``~/.claude/commands/``, ``~/.gemini/commands/``, etc.) by
``ensure_global_agent_commands()`` at CLI startup. Per-project copies are no
longer needed, but removing them must preserve any user customization the CLI
cannot prove safe to delete.

This migration removes a project-local command file only when the local file is
proven spec-kitty-generated by the version marker scan **and** the project is past
the command-globalization boundary, in one of two ways:

  1. **The project's own stamp answers** (#6954). ``.kittify/metadata.yaml`` dated at
     or above this migration's ``target_version`` is a project that already globalizes
     commands: the file is ours and obsolete, so it is removed without asking the
     operator's machine. Asking the machine first made the answer depend on *who* ran
     ``upgrade``: ``upgrade`` deliberately does not bootstrap ``~/.kittify`` (#3900),
     and ledger-diff re-evaluates a ``skipped`` record on every run, so on a machine
     whose first spec-kitty command is ``upgrade`` the same commit kept a file that
     another machine removed (ADR ``docs/adr/4.x/2026-10-17-1-explicit-migration-ledger.md``
     §3). The CLI installs the global copies at the next command either way.
  2. **The machine answers, for shapes with no usable stamp.** A project with no
     ``metadata.yaml``, or one that cannot be dated, keeps the historical checks: the
     global runtime (``~/.kittify/missions/``) must be present and the exact global
     replacement file must exist for the same agent/filename.

A file that lacks the version marker is user-authored or unproven: it is
preserved in place and reported for manual review (the only "held" case), on every
machine. A file that carries the marker but cannot be removed in the legacy shape
(global runtime or exact global replacement absent, or the unlink failed) is ours,
not customised: it is kept in place with a note and is NOT held for review.
Migrations are version-windowed (``MigrationRegistry.get_applicable``), so this
migration does not run again once the project is past it: a generated command kept
here stays project-local, and once the operator later gets the global copy both
exist (a local plus a global duplicate) until they delete the local one. That is
the accepted cost of not holding the whole upgrade commit (#5443). No backup/merge
UX is introduced here.
"""

from __future__ import annotations

from pathlib import Path

from packaging.version import InvalidVersion, Version

from specify_cli.runtime.home import get_kittify_home

from ..metadata import ProjectMetadata
from ..registry import MigrationRegistry
from .base import BaseMigration, MigrationResult
from .m_0_9_1_complete_lane_migration import get_agent_dirs_for_project
from kernel.paths import to_posix

_VERSION_MARKER_PREFIX = "<!-- spec-kitty-command-version:"
_VERSION_MARKER_HEAD_LINES = 15

_HOLD = "hold"
_KEEP = "keep"
_REMOVE = "remove"


def _agent_key_for_root(agent_root: str) -> str | None:
    """Return the agent key for a command-dir root, or ``None`` when it has none."""
    try:
        from specify_cli.agent_utils.directories import AGENT_DIR_TO_KEY  # noqa: PLC0415
    except Exception:
        return None
    key = AGENT_DIR_TO_KEY.get(agent_root)
    return key if isinstance(key, str) else None


class _SafeGlobalizeCommandsBase(BaseMigration):
    """Shared safe command-cleanup behavior used by multiple upgrade paths."""

    @staticmethod
    def _iter_agent_command_dirs(project_path: Path) -> list[tuple[str, str]]:
        """Return candidate command dirs, including legacy Codex prompt roots."""
        agent_dirs = list(get_agent_dirs_for_project(project_path))
        legacy_codex_dir = project_path / ".codex" / "prompts"
        if legacy_codex_dir.is_dir():
            agent_dirs.append((".codex", "prompts"))
        return agent_dirs

    def detect(self, project_path: Path) -> bool:
        """Return True if any project-local spec-kitty command file exists."""
        for agent_root, subdir in self._iter_agent_command_dirs(project_path):
            agent_dir = project_path / agent_root / subdir
            if not agent_dir.is_dir():
                continue
            for candidate in agent_dir.iterdir():
                if candidate.name.startswith("spec-kitty."):
                    return True
        return False

    def can_apply(self, project_path: Path) -> tuple[bool, str]:
        return True, ""

    @staticmethod
    def _global_runtime_present() -> bool:
        """Return True when the user-global runtime tree is available."""
        try:
            missions_dir = get_kittify_home() / "missions"
        except Exception:
            return False
        if not missions_dir.is_dir():
            return False
        return any(p.is_dir() for p in missions_dir.iterdir())

    @staticmethod
    def _global_command_file_present(agent_root: str, subdir: str, filename: str) -> bool:
        """Check that the exact global replacement file exists.

        The directory is asked of the canonical owner
        (:func:`specify_cli.runtime.agent_commands.get_global_command_dir`) rather than
        re-derived from ``Path.home() / agent_root / subdir``, which silently missed
        ``opencode``, ``llxprt`` and ``copilot``'s documented global roots. The
        hand-built shape is kept only for roots with no agent key (the legacy
        ``.codex/prompts`` root), where there is no canonical key to ask about.
        """
        agent_key = _agent_key_for_root(agent_root)
        if agent_key is not None:
            try:
                from specify_cli.runtime.agent_commands import (  # noqa: PLC0415
                    get_global_command_dir,
                )

                return bool((get_global_command_dir(agent_key) / filename).is_file())
            except Exception:
                return False
        try:
            global_agent_dir = Path.home() / agent_root / subdir
        except Exception:
            return False
        return (global_agent_dir / filename).is_file()

    def _is_past_globalization_boundary(self, project_path: Path) -> bool:
        """Return True when the project's own stamp says commands are already global.

        ``.kittify/metadata.yaml`` dated at or above this migration's
        ``target_version`` is the project-local evidence that the CLI that last
        touched this project installs commands globally -- so a version-marked
        project-local copy is ours and obsolete regardless of which machine runs the
        upgrade (#6954). The threshold is this subclass's ``target_version`` so the
        residue-safe sibling inherits the same rule without a second constant.

        A project we cannot date -- no metadata, an unparseable stamp, or an unquoted
        numeric stamp that YAML parses as a float -- is not evidence of a modern
        project: it keeps the legacy machine-driven answer.
        """
        metadata = ProjectMetadata.load(project_path / ".kittify")
        if metadata is None:
            return False
        try:
            return Version(metadata.version) >= Version(self.target_version)
        except (InvalidVersion, TypeError):
            return False

    @staticmethod
    def _is_generated_file(path: Path) -> bool:
        """Return True when the file head contains a spec-kitty version marker."""
        try:
            content = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            return False
        for line in content.splitlines()[:_VERSION_MARKER_HEAD_LINES]:
            if line.strip().startswith(_VERSION_MARKER_PREFIX):
                return True
        return False

    @staticmethod
    def _rel(path: Path, project_path: Path) -> str:
        return to_posix(path.relative_to(project_path))

    def _preserve(
        self,
        *,
        changes: list[str],
        preserved_paths: list[str],
        rel: str,
        reason: str,
        dry_run: bool,
    ) -> None:
        verb = "Would preserve" if dry_run else "Preserved"
        changes.append(f"{verb}: {rel} ({reason})")
        preserved_paths.append(rel)

    def _classify(
        self,
        *,
        target: Path,
        agent_root: str,
        subdir: str,
        runtime_present: bool,
        globalized: bool = False,
    ) -> tuple[str, str]:
        """Decide what to do with one project-local command file.

        Returns ``(action, reason)`` where *action* is ``"hold"`` (no version marker:
        operator-authored or unproven, held for manual review), ``"keep"`` (generated,
        but the global runtime or exact global replacement is absent) or ``"remove"``.
        The marker check comes first: only a missing marker means "customised", on
        every machine. When *globalized* is true the project's own stamp has already
        answered that commands are global, so the machine-driven checks are not asked.
        """
        if not self._is_generated_file(target):
            return _HOLD, "no version marker (user-authored or unproven file)"
        if not globalized:
            if not runtime_present:
                return _KEEP, "global runtime (~/.kittify/missions/) not found"
            if not self._global_command_file_present(agent_root, subdir, target.name):
                return _KEEP, f"no global equivalent at ~/{agent_root}/{subdir}/{target.name}"
        return _REMOVE, ""

    def apply(self, project_path: Path, dry_run: bool = False) -> MigrationResult:
        changes: list[str] = []
        warnings: list[str] = []
        preserved_paths: list[str] = []
        globalized = self._is_past_globalization_boundary(project_path)
        runtime_present = True if globalized else self._global_runtime_present()
        verb_keep = "Would keep" if dry_run else "Kept"

        for agent_root, subdir in self._iter_agent_command_dirs(project_path):
            agent_dir = project_path / agent_root / subdir
            if not agent_dir.is_dir():
                continue

            targets = sorted(candidate for candidate in agent_dir.iterdir() if candidate.name.startswith("spec-kitty."))
            for target in targets:
                rel = self._rel(target, project_path)
                action, reason = self._classify(
                    target=target,
                    agent_root=agent_root,
                    subdir=subdir,
                    runtime_present=runtime_present,
                    globalized=globalized,
                )
                if action == _HOLD:
                    self._preserve(
                        changes=changes,
                        preserved_paths=preserved_paths,
                        rel=rel,
                        reason=reason,
                        dry_run=dry_run,
                    )
                    continue
                if action == _KEEP:
                    changes.append(f"{verb_keep}: {rel} (generated; {reason})")
                    continue

                if dry_run:
                    changes.append(f"Would remove: {rel}")
                    continue

                try:
                    target.chmod(target.stat().st_mode | 0o222)
                    target.unlink()
                    changes.append(f"Removed: {rel}")
                except OSError as exc:
                    # Ours (it carries the marker), just not removable: kept, not held.
                    changes.append(f"Kept: {rel} (generated; unlink failed: {exc})")
                    warnings.append(f"Could not remove {rel}: {exc}")

            if not dry_run and agent_dir.is_dir():
                try:
                    agent_dir.rmdir()
                    changes.append(f"Removed empty directory: {self._rel(agent_dir, project_path)}")
                except OSError:
                    pass

        return MigrationResult(
            success=True,
            changes_made=changes,
            warnings=warnings,
            manual_review_required=bool(preserved_paths),
            preserved_paths=preserved_paths,
        )


@MigrationRegistry.register
class GlobalizeCommandsMigration(_SafeGlobalizeCommandsBase):
    """Safely remove per-project spec-kitty command files."""

    migration_id = "3.1.2_globalize_commands"
    description = "Safely remove per-project spec-kitty command files after global install"
    target_version = "3.1.2"
