class _FrozenTreeHashProver:
    """Proves a skill directory removable when it is a byte copy of the shipped source."""

    def __init__(self, hashes: Mapping[str, str]) -> None:
        self._hashes = hashes

    def prove(self, path: Path, project_path: Path) -> OwnershipProof | None:
        if not self._hashes or path.is_symlink() or not path.is_dir():
            return None
        from specify_cli.skills.manifest import compute_content_hash

        found: dict[str, str] = {}
        for member in sorted(path.rglob("*")):
            if member.is_symlink():
                return None
            if member.is_file():
                try:
                    found[member.relative_to(path).as_posix()] = compute_content_hash(member)
                except OSError:
                    return None
        if found != {rel: f"sha256:{digest}" for rel, digest in self._hashes.items()}:
            return None
        return OwnershipProof("canonical_content", f"shipped-skill-hash:{path.relative_to(project_path).as_posix()}")


@dataclass(frozen=True)
class SkillCopy:
    """One installed directory named after a removed skill."""

    path: Path
    name: str

    def rel(self, project: Path) -> str:
        return self.path.relative_to(project).as_posix()


def _configured_skill_roots(project: Path) -> list[str]:
    from specify_cli.core.agent_config import AgentConfigError, load_agent_config
    from specify_cli.core.config import AGENT_SKILL_CONFIG

    try:
        agents = load_agent_config(project).available
    except AgentConfigError as exc:
        raise MigrationStateUnreadableError(f"{exc}; fix the file, then run `spec-kitty upgrade` again") from exc
    roots: list[str] = []
    for agent in agents:
        configured = AGENT_SKILL_CONFIG.get(agent, {}).get("skill_roots")
        for root in configured if isinstance(configured, list) else []:
            normalised = root.rstrip("/")
            if normalised not in roots:
                roots.append(normalised)
    return roots


def _shipped_skill_names() -> frozenset[str]:
    """Names the installed CLI's skill catalog still ships (the upgrade finalizer installs those).

    Raises:
        MigrationStateUnreadableError: no shipped skill catalog is found, so a
            removed name the CLI still ships cannot be told apart; fail closed
            rather than remove a skill the finalizer would reinstall.
    """
    from specify_cli.skills.catalog import resolve_builtin_skill_catalog

    registry = resolve_builtin_skill_catalog()
    if registry is None:
        raise MigrationStateUnreadableError(
            "the installed CLI ships no skill catalog, so the removed skills it still ships cannot be told apart; "
            "reinstall spec-kitty, then run `spec-kitty upgrade` again"
        )
    return frozenset(skill.name for skill in registry.discover_skills())


def find_removed_skill_copies(project_path: Path) -> list[SkillCopy]:
    """Every ``<configured skill root>/<removed name>`` present in *project_path* (nothing is written).

    A name the installed catalog still ships is skipped: the upgrade finalizer
    would install it again right after, so removing it would only churn.
    """
    shipped = _shipped_skill_names()
    names = [name for name in REMOVED_SKILL_NAMES if name not in shipped]
    copies: list[SkillCopy] = []
    for root in _configured_skill_roots(project_path) if names else []:
        base = project_path / root
        if not base.is_dir():
            continue
        copies.extend(SkillCopy(base / name, name) for name in names if os.path.lexists(base / name))
    return copies


def _prover(name: str) -> AnyProver:
    return AnyProver([ManifestProver(), _FrozenTreeHashProver(SHIPPED_SKILL_HASHES.get(name, {}))])


def _drop_manifest_entries(project: Path, removed: list[str]) -> None:
    """Drop the manifest entries of every removed directory (project-relative paths)."""
    from specify_cli.skills.manifest import load_manifest, save_manifest

    manifest = load_manifest(project, strict=True)
    if manifest is None:
        return
    prefixes = tuple(f"{rel}/" for rel in removed)
    kept = [entry for entry in manifest.entries if not entry.installed_path.startswith(prefixes)]
    if len(kept) != len(manifest.entries):
        manifest.entries = kept
        save_manifest(manifest, project)


def _remove_one(project: Path, copy: SkillCopy, report: CutoverReport, *, dry_run: bool) -> bool:
    """Remove or keep *copy*; ``True`` once it is settled (removed or kept), ``False`` on an error."""
    rel = copy.rel(project)
    try:
        verdict = guard_destructive_removal(copy.path, project, prover=_prover(copy.name), is_tree=True, dry_run=dry_run)
    except OSError as exc:
        report.errors.append(f"{rel} could not be removed ({exc}); close any program holding it, then run `spec-kitty upgrade` again")
        return False
    if verdict.owned:
        report.skills_removed.append(f"{rel} ({copy.name}; {verdict.reason})")
        return True
    report.skills_kept.append(
        f"{rel} ({copy.name}; edited or not a shipped copy, left in place and no longer managed by spec-kitty; remove it by hand once you no longer need it)"
    )
    report.preserved_paths.append(rel)
    return True


def remove_skill_copies(project_path: Path, *, dry_run: bool) -> CutoverReport:
    """Remove every proven copy of a removed skill (unless *dry_run*); keep and report the rest.

    Every settled copy, removed or kept, leaves the skills manifest: a removed
    one so no orphan entry remains, a kept one so it becomes user-owned. A copy
    whose removal failed keeps its entries, so the next upgrade can still prove it.
    """
    report = CutoverReport()
    settled = [copy.rel(project_path) for copy in find_removed_skill_copies(project_path) if _remove_one(project_path, copy, report, dry_run=dry_run)]
    if settled and not dry_run:
        try:
            _drop_manifest_entries(project_path, settled)
        except (OSError, ValueError) as exc:
            report.errors.append(f".kittify/skills-manifest.json could not be updated ({exc}); run `spec-kitty upgrade` again")
    return report
