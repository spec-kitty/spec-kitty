"""Installed copies of removed skills, for the charter-pack cutover (FR-012 step 7, FR-008, #3732).

Contract: ``kitty-specs/charter-pack-cutover-01M491G6/contracts/upgrade-migration.md`` step 7.

For each project skill root of each configured agent
(``AGENT_SKILL_CONFIG[agent]["skill_roots"]``, deduplicated; a root that does
not exist is skipped, never created), every ``<root>/<removed name>/`` is
removed through :func:`specify_cli.asset_preservation.guard_destructive_removal`
when its ownership is proven, either

* by the managed-skills manifest (:class:`~specify_cli.asset_preservation.ManifestProver`:
  every file has an entry whose hash matches), or
* by :class:`_FrozenTreeHashProver`: the tree holds exactly the files a shipped
  source held and each one hashes to :data:`SHIPPED_SKILL_HASHES`.

Anything else (an edited copy, an extra file, a symlink) stays in place and is
reported once (``skills_kept``, ``preserved_paths``). A removed copy's entries are
dropped from ``.kittify/skills-manifest.json`` so no orphan entry remains, and so
are a kept copy's (owner ruling A, US4): the kept copy becomes user-owned, so the
upgrade finalizer never offers to overwrite it and later upgrades exit 0. A
name the installed CLI still ships is left alone (the upgrade finalizer would
reinstall it); every name is live once its source is deleted (FR-008).

:data:`SHIPPED_SKILL_HASHES` are the sha256 of every installable file
(``SKILL.md``, ``references/``, ``scripts/``, ``assets/``) under
``src/charter/offering/skills/<name>/`` as of the cutover, generated by a
scratch script from those sources; installed copies are byte copies of them.
Limitation: copies installed by an older release whose bytes differ are not
covered, so an unmanifested older copy is kept and reported (the safe
direction). ``spec-kitty-constitution-doctrine`` ships no source here: only a
manifested copy of it is removed.
"""

