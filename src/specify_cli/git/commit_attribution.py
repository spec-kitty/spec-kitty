"""The operator's commit attribution trailer, resolved once for the Op auto-commit (#7013).

The ``op(...)`` commit is generated by the CLI, so the operator's
``Co-Authored-By`` has to be appended there or an agent has to rebuild the commit
by hand. This module is the ONE owner of that decision:

* :func:`resolve_co_author_trailer` returns the trailer line
  (``Co-Authored-By: Name <email>``) or ``None`` when nothing is configured;
* :class:`InvalidCoAuthor` is the configuration/usage error, carrying the key the
  operator must fix.

Precedence: an explicit per-close value (``profile-invocation complete
--co-author``, or the executor argument behind it) wins over the repository's
standing ``commit.co_author`` in ``.kittify/config.yaml``.

The configured value is read through the same authority as the other
``.kittify/config.yaml`` behaviour keys (``review.test_command``,
``review.test_timeout_seconds``): a safe YAML load of that one file. It adds
one optional key, ``commit.co_author``. A missing file or a missing key means "no trailer", never
an error — the auto-commit in a consumer repository must keep behaving exactly as
it did before this feature existed. A key that is present but unparseable is a
defect and refuses the commit (the caller reports it as
``OpCommitOutcome.refusal``); it never silently commits unattributed.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from pathlib import Path

from ruamel.yaml import YAML
from ruamel.yaml.error import YAMLError

__all__ = ["InvalidCoAuthor", "resolve_co_author_trailer"]

#: The trailer key this module owns. Git's own spelling is case-insensitive for
#: trailers, so a value that already carries it is accepted.
TRAILER_KEY = "Co-Authored-By"
#: The configuration key, named in every error message so the fix is obvious.
CONFIG_KEY = "commit.co_author"
CONFIG_RELATIVE_PATH = Path(".kittify") / "config.yaml"

_TRAILER_PREFIX_RE = re.compile(rf"^{re.escape(TRAILER_KEY)}\s*:\s*", flags=re.IGNORECASE)
#: ``Name <local@domain>`` — a display name (at least one character, no newlines)
#: and one address, which is exactly what a git trailer value must look like.
_IDENTITY_RE = re.compile(r"^(?P<name>[^<>\r\n][^<>\r\n]*?)\s*<(?P<email>[^<>\s@]+@[^<>\s@]+)>$")


class InvalidCoAuthor(ValueError):
    """A ``Co-Authored-By`` value cannot be used, or nothing it names is usable.

    ``source`` is the key the operator must fix: ``commit.co_author`` for a
    configured value, ``--co-author`` for a value passed for one close.
    """

    def __init__(self, message: str, *, source: str = CONFIG_KEY) -> None:
        self.source = source
        super().__init__(message)


def _strip_trailer_key(value: str) -> str:
    """Return the identity part of *value*, dropping a leading ``Co-Authored-By:``."""
    return _TRAILER_PREFIX_RE.sub("", value, count=1).strip()


def _validate(identity: str, *, source: str) -> str:
    """Return ``Co-Authored-By: Name <email>`` for *identity*, or raise."""
    match = _IDENTITY_RE.match(identity)
    if match is None:
        raise InvalidCoAuthor(
            f"{source} must be 'Name <email>' (an optional leading '{TRAILER_KEY}:' is accepted), got {identity!r}",
            source=source,
        )
    return f"{TRAILER_KEY}: {match.group('name').strip()} <{match.group('email')}>"


def _configured_value(repo_root: Path) -> str | None:
    """The raw ``commit.co_author`` string, or ``None`` when unset/blank."""
    path = repo_root / CONFIG_RELATIVE_PATH
    try:
        config = YAML(typ="safe").load(path) if path.exists() else None
    except (YAMLError, OSError, UnicodeDecodeError) as exc:
        raise InvalidCoAuthor(f"Cannot read {CONFIG_KEY} from {path}: {exc}") from exc
    if config is None:
        return None
    if not isinstance(config, Mapping):
        raise InvalidCoAuthor(f"{CONFIG_RELATIVE_PATH} must be a mapping to carry {CONFIG_KEY}")
    section = config.get("commit")
    if section is None:
        return None
    if not isinstance(section, Mapping):
        raise InvalidCoAuthor(f"commit must be a mapping to carry {CONFIG_KEY}")
    raw = section.get("co_author")
    if raw is None:
        return None
    if not isinstance(raw, str):
        raise InvalidCoAuthor(f"{CONFIG_KEY} must be a string 'Name <email>', got {type(raw).__name__}")
    value = raw.strip()
    return value or None


def resolve_co_author_trailer(repo_root: Path, explicit: str | None = None) -> str | None:
    """Return ``Co-Authored-By: Name <email>`` for this close, or ``None``.

    Args:
        repo_root: The checkout whose ``.kittify/config.yaml`` is read.
        explicit: A per-close value that overrides the configured one. An empty
            or whitespace-only value is refused rather than ignored: a caller
            that asked for attribution and supplied nothing has a defect.

    Raises:
        InvalidCoAuthor: the explicit value is blank or unusable, the configured
            value is present but unusable, or the configuration cannot be read.
    """
    if explicit is not None:
        identity = _strip_trailer_key(explicit)
        if not identity:
            raise InvalidCoAuthor("--co-author cannot be empty: pass 'Name <email>' or omit it", source="--co-author")
        return _validate(identity, source="--co-author")

    configured = _configured_value(repo_root)
    if configured is None:
        return None
    return _validate(_strip_trailer_key(configured), source=CONFIG_KEY)
