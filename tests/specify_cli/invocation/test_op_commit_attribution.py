"""Operator attribution on the Op auto-commit (#7013).

The `op(...)` commit is generated by the executor, never by the operator, so the
operator's `Co-Authored-By` trailer has to be added there. These tests drive the
production close path on a real git fixture and read the commit message back:

* `complete_invocation(..., closed_by="agent")` → the per-record commit;
* `complete_invocation(..., closed_by="doctor_sweep")` → the closure-spine commit.

Every refusal/absence assertion is paired, on the same fixture, with an assertion
that the probe can observe the trailer when it is configured (tactic
`acceptance-criteria-non-vacuity`).
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path
from typing import TYPE_CHECKING

import pytest

if TYPE_CHECKING:
    from typer.testing import Result

from specify_cli.git.commit_attribution import InvalidCoAuthor, resolve_co_author_trailer
from specify_cli.invocation.executor import OpCommitOutcome, OpCompletedEvent, ProfileInvocationExecutor
from specify_cli.invocation.record import OpStartedEvent
from specify_cli.invocation.writer import EVENTS_DIR, InvocationWriter
from tests.specify_cli.invocation._op_git import checkout_issue_branch, run_git, track_op_record_on_current_branch

pytestmark = [pytest.mark.integration, pytest.mark.git_repo]

ULID = "01M6EJV5AABBCCDDEEFFGGHHJK"
OPERATOR = "Ivan Melck <22272470+Ivan-Melck@users.noreply.github.com>"
OTHER_OPERATOR = "Someone Else <someone@example.invalid>"


# ---------------------------------------------------------------------------
# Fixtures
# ---------------------------------------------------------------------------


def _init_repo(path: Path) -> None:
    """A git repo whose primary branch tracks Op records (so the commit happens).

    The identity is repo-local: the fixture must not depend on the developer's
    global git config (a machine without one fails every commit here).
    """
    subprocess.run(["git", "init", "-b", "main", str(path)], check=True, capture_output=True)
    run_git(path, "config", "user.name", "Op Attribution Test")
    run_git(path, "config", "user.email", "op-attribution@example.invalid")
    (path / "README.md").write_text("test repo\n", encoding="utf-8")
    run_git(path, "add", "README.md")
    run_git(path, "commit", "--no-verify", "-m", "init")
    track_op_record_on_current_branch(path)
    checkout_issue_branch(path)


def _write_config(path: Path, *, co_author: str | None) -> None:
    kittify = path / ".kittify"
    kittify.mkdir(parents=True, exist_ok=True)
    body = "{}\n" if co_author is None else f"commit:\n  co_author: {json.dumps(co_author)}\n"
    (kittify / "config.yaml").write_text(body, encoding="utf-8")


def _open_op(path: Path, *, invocation_id: str = ULID) -> None:
    InvocationWriter(path).write_started(
        OpStartedEvent(
            invocation_id=invocation_id,
            profile_id="python-pedro",
            action="implement",
            request_text="implement WP01",
            actor="claude",
            mode_of_work="task_execution",
            governance_context_hash="0123456789abcdef",
            governance_context_available=True,
            started_at="2026-11-02T12:00:00+00:00",
        )
    )


def _close(path: Path, *, invocation_id: str = ULID, co_author: str | None = None) -> tuple[OpCompletedEvent, OpCommitOutcome | None]:
    executor = ProfileInvocationExecutor(path)
    completed = executor.complete_invocation(
        invocation_id,
        outcome="done",
        closed_by="agent",
        co_author=co_author,
    )
    return completed, executor.last_op_commit


def _commit_message(path: Path, ref: str = "HEAD") -> str:
    return run_git(path, "log", "-1", "--format=%B", ref)


# ---------------------------------------------------------------------------
# The configured trailer rides the per-record commit
# ---------------------------------------------------------------------------


def test_configured_co_author_rides_the_per_record_commit(tmp_path: Path) -> None:
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author=OPERATOR)
    _open_op(tmp_path)

    _completed, outcome = _close(tmp_path)

    assert outcome is not None and outcome.committed is True
    assert _commit_message(tmp_path).rstrip().endswith(f"Co-Authored-By: {OPERATOR}")


def test_configured_co_author_rides_the_doctor_sweep_spine_commit(tmp_path: Path) -> None:
    """The sweep closes pre-existing records on the spine; that commit is attributed too."""
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author=OPERATOR)
    _open_op(tmp_path)

    executor = ProfileInvocationExecutor(tmp_path)
    executor.complete_invocation(ULID, outcome="abandoned", closed_by="doctor_sweep")

    assert executor.last_op_commit is not None and executor.last_op_commit.committed is True
    assert _commit_message(tmp_path).rstrip().endswith(f"Co-Authored-By: {OPERATOR}")


# ---------------------------------------------------------------------------
# No configuration → the pre-change message, byte for byte
# ---------------------------------------------------------------------------


def test_no_configured_co_author_keeps_the_pre_change_message(tmp_path: Path) -> None:
    """A consumer repository with no `commit.co_author` gets exactly the old message."""
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author=None)
    _open_op(tmp_path)

    _completed, outcome = _close(tmp_path)

    assert outcome is not None and outcome.committed is True
    message = _commit_message(tmp_path)
    assert "Co-Authored-By:" not in message
    assert message.strip().startswith("op(python-pedro): implement [")
    assert message.strip().endswith("]")


# ---------------------------------------------------------------------------
# An explicit value wins over the configuration
# ---------------------------------------------------------------------------


def test_explicit_co_author_overrides_the_configured_value(tmp_path: Path) -> None:
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author=OPERATOR)
    _open_op(tmp_path)

    _completed, outcome = _close(tmp_path, co_author=OTHER_OPERATOR)

