@pytest.mark.parametrize("blank", ["", "   ", "\n"])
def test_blank_explicit_co_author_is_refused_before_any_write(tmp_path: Path, blank: str) -> None:
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author=None)
    _open_op(tmp_path)
    head_before = run_git(tmp_path, "rev-parse", "HEAD")

    with pytest.raises(InvalidCoAuthor):
        _close(tmp_path, co_author=blank)

    # Nothing was written or committed: the close is refused before the record.
    assert run_git(tmp_path, "rev-parse", "HEAD") == head_before
    record = tmp_path / EVENTS_DIR / f"{ULID}.jsonl"
    assert "completed" not in record.read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# A malformed configuration refuses the commit, visibly, without losing the trail
# ---------------------------------------------------------------------------


def test_malformed_configured_co_author_refuses_the_commit_and_names_the_key(tmp_path: Path) -> None:
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author="not-an-identity")
    _open_op(tmp_path)
    head_before = run_git(tmp_path, "rev-parse", "HEAD")

    completed, outcome = _close(tmp_path)

    # The close succeeded and the trail is durable …
    assert completed.outcome == "done"
    record = tmp_path / EVENTS_DIR / f"{ULID}.jsonl"
    assert '"event": "completed"' in record.read_text(encoding="utf-8")
    # … the commit did not happen, and the refusal names the configuration key …
    assert outcome is not None
    assert outcome.committed is False
    assert outcome.refusal is not None and "commit.co_author" in outcome.refusal
    # … and nothing unattributed landed in history.
    assert run_git(tmp_path, "rev-parse", "HEAD") == head_before


def test_trailer_already_spelled_as_a_trailer_is_not_double_prefixed(tmp_path: Path) -> None:
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author=f"Co-Authored-By: {OPERATOR}")
    _open_op(tmp_path)

    _completed, outcome = _close(tmp_path)

    assert outcome is not None and outcome.committed is True
    message = _commit_message(tmp_path)
    assert message.count("Co-Authored-By:") == 1
    assert f"Co-Authored-By: {OPERATOR}" in message


# ---------------------------------------------------------------------------
# The CLI surface: `profile-invocation complete --co-author`
# ---------------------------------------------------------------------------


def _run_cli_complete(project: Path, *args: str) -> Result:
    from unittest.mock import patch

    from typer.testing import CliRunner

    from specify_cli import app as cli_app

    with patch("specify_cli.cli.commands.profile_invocation.find_repo_root", return_value=project):
        return CliRunner().invoke(cli_app, ["profile-invocation", "complete", *args])


def test_cli_co_author_overrides_the_configured_value(tmp_path: Path) -> None:
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author=OPERATOR)
    _open_op(tmp_path)

    result = _run_cli_complete(tmp_path, "--invocation-id", ULID, "--outcome", "done", "--co-author", OTHER_OPERATOR)

    assert result.exit_code == 0, result.output
    message = _commit_message(tmp_path)
    assert f"Co-Authored-By: {OTHER_OPERATOR}" in message
    assert OPERATOR not in message


def test_cli_blank_co_author_is_a_usage_error_before_any_write(tmp_path: Path) -> None:
    _init_repo(tmp_path)
    _write_config(tmp_path, co_author=OPERATOR)
    _open_op(tmp_path)
    head_before = run_git(tmp_path, "rev-parse", "HEAD")

    result = _run_cli_complete(tmp_path, "--invocation-id", ULID, "--outcome", "done", "--co-author", "   ")

    assert result.exit_code == 2, result.output
    assert "--co-author" in result.output
    assert run_git(tmp_path, "rev-parse", "HEAD") == head_before
    record = tmp_path / EVENTS_DIR / f"{ULID}.jsonl"
    assert "completed" not in record.read_text(encoding="utf-8")


