class TestResolveCoAuthorTrailer:
    def test_absent_file_returns_none(self, tmp_path: Path) -> None:
        assert resolve_co_author_trailer(tmp_path) is None

    def test_absent_key_returns_none(self, tmp_path: Path) -> None:
        _write_config(tmp_path, co_author=None)
        assert resolve_co_author_trailer(tmp_path) is None

    def test_plain_identity_is_prefixed(self, tmp_path: Path) -> None:
        _write_config(tmp_path, co_author=OPERATOR)
        assert resolve_co_author_trailer(tmp_path) == f"Co-Authored-By: {OPERATOR}"

    def test_prefixed_value_is_normalised_once(self, tmp_path: Path) -> None:
        _write_config(tmp_path, co_author=f"Co-Authored-By: {OPERATOR}")
        assert resolve_co_author_trailer(tmp_path) == f"Co-Authored-By: {OPERATOR}"

    def test_blank_configured_value_is_absent(self, tmp_path: Path) -> None:
        _write_config(tmp_path, co_author="   ")
        assert resolve_co_author_trailer(tmp_path) is None

    @pytest.mark.parametrize("bad", ["not-an-identity", "Name", "Name <not-an-email>", "<only@example.invalid>"])
    def test_malformed_value_raises_naming_the_key(self, tmp_path: Path, bad: str) -> None:
        _write_config(tmp_path, co_author=bad)
        with pytest.raises(InvalidCoAuthor, match="commit.co_author"):
            resolve_co_author_trailer(tmp_path)

    def test_newline_in_display_name_is_refused(self, tmp_path: Path) -> None:
        """A newline in the display name would inject an extra trailer; refuse it."""
        _write_config(tmp_path, co_author="Ivan\n\nSigned-off-by: Evil <evil@example.com>")
        with pytest.raises(InvalidCoAuthor, match="commit.co_author"):
            resolve_co_author_trailer(tmp_path)

    def test_explicit_value_wins_and_is_validated(self, tmp_path: Path) -> None:
        _write_config(tmp_path, co_author=OPERATOR)
        assert resolve_co_author_trailer(tmp_path, explicit=OTHER_OPERATOR) == f"Co-Authored-By: {OTHER_OPERATOR}"
        with pytest.raises(InvalidCoAuthor, match="--co-author"):
            resolve_co_author_trailer(tmp_path, explicit="not-an-identity")

    def test_unreadable_config_is_a_configuration_error(self, tmp_path: Path) -> None:
        kittify = tmp_path / ".kittify"
        kittify.mkdir(parents=True)
        (kittify / "config.yaml").write_text("commit: [unclosed\n", encoding="utf-8")
        with pytest.raises(InvalidCoAuthor, match="commit.co_author"):
            resolve_co_author_trailer(tmp_path)
