def shard_roster_non_vacuity_violation(
    roster_job_keys: tuple[str, ...],
    real_job_keys: Iterable[str],
) -> str | None:
    """Shared roster-vs-workflow non-vacuity/count-match check (landing pass
    #5244, LAND-PAT-006).

    The roster must be non-empty, and its declared job-key count must equal
    the number of real ``JOB_KEY_PREFIX``-shaped keys ``real_job_keys`` (any
    iterable of job-key strings -- typically a parsed workflow's ``jobs:``
    mapping keys) actually carries. Returns a message describing the
    violation, or ``None`` when they agree.

    Collapses three previously independent copies of this exact check --
    ``test_interpreter_matrix_env_pinning.py``,
    ``test_migration_robustness.py``, and
    ``test_interpreter_shard_coverage.py`` -- each of which separately
    hardcoded the ``interpreter-matrix-shard-`` job-key prefix as a literal
    (a fourth restatement of the naming convention :data:`JOB_KEY_PREFIX`
    now owns) and re-derived the same count comparison. Each of those three
    call sites keeps its own guard test and mutation control; only the
    comparison itself is shared.
    """
    if not roster_job_keys:
        return "INTERPRETER_SHARD_JOB_KEYS must not be empty"
    real_shard_job_keys = {key for key in real_job_keys if key.startswith(JOB_KEY_PREFIX)}
    if len(real_shard_job_keys) != len(roster_job_keys):
        return (
            f"roster declares {len(roster_job_keys)} shard job key(s) {sorted(roster_job_keys)} but "
            f"the workflow defines {len(real_shard_job_keys)} {JOB_KEY_PREFIX}* job(s) {sorted(real_shard_job_keys)}"
        )
    return None
