"""Shard-identity roster for the nightly ``interpreter-matrix`` split (#4951, FR-016).

The single, always-timing-out ``interpreter-matrix`` job in
``ci-nightly.yml`` is replaced by N independent ``interpreter-matrix-shard-<N>``
jobs, each running a disjoint slice of ``pytest -m "fast or unit"`` on Python
3.13. This module is the SINGLE SOURCE OF TRUTH for shard identity: which
job keys exist, which test paths each one owns, and which ``--suite-key``
each shard's escalation call must use.

``tests/architectural/test_interpreter_shard_coverage.py`` reads
:data:`INTERPRETER_SHARDS` to:

1. Prove the union of every shard's real collected node-ids equals the full
   ``fast or unit`` 3.13 selection, with zero duplicates and zero gaps
   (FR-004/NFR-002).
2. Diff this roster's declared job keys against ``ci-nightly.yml``'s real
   ``jobs:`` keys, so a shard silently dropped from the job list (while
   remaining declared here) is a loud, named failure (FR-016) -- distinct
   from a shard that is present in the job list but collects 0 tests
   (FR-005).

``tests/architectural/test_performance_marker_guard.py`` also imports
:data:`INTERPRETER_SHARDS`/``INTERPRETER_SHARD_JOB_KEYS`` from here (dynamic
discovery, not a second hardcoded literal list) so shard identity is never
declared in more than one place.

Relationship to #5201's registry-derived lane (landing pass #5244,
LAND-PAT-007): these shards are an INTERPRETER-AXIS lane over ALL of
``fast or unit`` on Python 3.13, orthogonal to and independent of
``.github/ci-module-registry.yml``'s ``out_of_matrix_test_dirs``; their
overlap with the ``specify-cli-out-of-matrix`` job's ``tests/specify_cli``
subtrees (which run on the default interpreter instead) is intentional
complementary-interpreter coverage, not a double-run.

**REAL boundaries (NFR-006), derived from run 1's measurement (2026-09-27,
workflow_dispatch run 36294808024 on `ubuntu-24.04`, mode=full):**

- Shards 1-2 (`tests/unit tests/status tests/cli` /
  `tests/specify_cli/runtime tests/charter tests/kernel`) are UNCHANGED from
  the initial placeholder guess -- run 1 measured their real "Run fast/unit
  suite" step wall-clock directly: shard 1 = 351s (2203 collected), shard 2 =
  639s (3538 collected). Both comfortably fit a real budget.
- The initial placeholder shard 3 ("everything else", 29710 collected tests)
  was run 1's SMOKING GUN: its "Run fast/unit suite" step ran 46m19s (2779s)
  and its JOB-LEVEL conclusion was `cancelled` at the 45-minute cap -- a
  badly-imbalanced partition exactly as plan.md SS B anticipated. It is
  therefore split further, here, into 4 new shards (3-6) using a FRESH local
  `pytest --collect-only -q -m "fast or unit"` capture of that same
  "everything else" scope (29710 real node-ids, one collection call,
  2026-09-27), bucketed by top-level `tests/<dir>` (or `tests/specify_cli/<dir>`
  one level deeper, since `tests/specify_cli` alone was 14155/29710 -- 40%
  of the remaining total, too coarse a single unit), then partitioned into 4
  bins via a **simple greedy largest-first-to-smallest-bin (LPT) pass over
  this ONE fresh, real count list** -- this is NOT ledger SK-247's rejected
  mechanism: SK-247's defect is a COMMITTED duration list paired
  POSITIONALLY with node ids that goes stale as the suite changes and is
  never re-verified against a live recount; this partition is a ONE-TIME,
  human-reviewed grouping computed directly from a fresh collection in the
  SAME session that authors it, with no committed/stale duration file
  anywhere in this mechanism, and the coverage-completeness test
  (`test_interpreter_shard_coverage.py`) independently re-verifies, on every
  run, that the roster's declared paths still union to exactly the live full
  selection -- so even if the suite's directories drift after this roster is
  written, a real gap or overlap is caught immediately rather than silently
  trusted. Bins came out to 7428/7428/7427/7427 collected tests -- within 1
  test of perfectly even.
- Reproduction (corrected, landing pass #5244, LAND-PAT-005): no committed
  script performs this partition end-to-end -- `tracer-design-decisions.md`'s
  "Shard boundary redraw (T009)" section describes the METHOD in PROSE only
  ("generated by a one-off script", never itself committed or named by path).
  To regenerate this split by hand: (1) `pytest --collect-only -q -m "fast or
  unit" tests --ignore=<shard-1-paths> --ignore=<shard-2-paths>` to reproduce
  the "everything else" scope's real node-ids; (2) bucket those node-ids by
  top-level `tests/<dir>` (one level deeper, `tests/specify_cli/<dir>`, for
  any bucket too coarse to balance against); (3) feed each bucket's
  collected-test COUNT (not duration -- this partition balances test
  *counts*, never a duration list, which is exactly what ledger SK-247's
  rejected mechanism did) into
  `test_module_shard_registry.py::_lpt_bin_pack`, the SAME greedy
  largest-first-to-smallest-bin (LPT) algorithm this redraw used, into as
  many bins as new shards are wanted. `_lpt_bin_pack` takes `list[float]`, so
  pass bucket sizes as floats. Re-verify the result the same way this roster
  is continuously re-verified: `test_interpreter_shard_coverage.py`'s
  coverage-completeness test independently proves, on every run, that the
  roster's declared paths still union to exactly the live full selection --
  so a stale or mis-bucketed regeneration is a loud, named CI failure, not a
  silently trusted one.

Per-shard `timeout-minutes` (landing pass #5244, LAND-PAT-005; re-derived
#5378): the actual values live in ONE place -- each shard job's own
`timeout-minutes:` key in `ci-nightly.yml` -- and are deliberately NOT
restated here, so this docstring can never drift from the committed
workflow. The recorded derivation (measured maximum suite wall-clock, the
runs it came from, and the headroom formula) is the structured
`# headroom (#5378)` comment directly above each `timeout-minutes:` line in
`ci-nightly.yml`; `tests/ci/test_nightly_timeout_headroom.py` fails if a cap
falls below its own comment's formula.
"""

from __future__ import annotations

import re
