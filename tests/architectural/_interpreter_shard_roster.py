# The ``job_key`` prefix every shard in this roster must follow --
# ``interpreter-matrix-shard-<N>``. Landing pass #5244 (LAND-PAT-006): the
# SINGLE place this literal is declared -- three call sites
# (``test_interpreter_matrix_env_pinning.py``,
# ``test_migration_robustness.py``, ``test_interpreter_shard_coverage.py``)
# each independently hardcoded it a fourth time before this.
JOB_KEY_PREFIX = "interpreter-matrix-shard-"
# Every derived name on `InterpreterShard` below (exit var, junit filename,
# artifact name, lane label) is computed from `<N>` alone, so this single
# regex (built from `JOB_KEY_PREFIX`) is the one place that shape is parsed.
_JOB_KEY_RE = re.compile(re.escape(JOB_KEY_PREFIX) + r"(\d+)")


@dataclass(frozen=True)
class InterpreterShard:
    """One nightly interpreter-matrix shard's declared identity.

    ``job_key`` must match ``ci-nightly.yml``'s ``jobs:`` key for this shard
    EXACTLY -- this is what lets the coverage-completeness check diff this
    roster against the live workflow file by simple set comparison.

    The properties below (``shard_number``, ``exit_var``, ``junit_filename``,
    ``artifact_name``, ``lane_label``) are the roster-level derivations of
    every per-shard naming convention the workflow and its guard tests rely
    on. Before this, each convention was independently re-derived by a
    different test module with its own regex/``.replace``/``rsplit`` --
    a copy-paste hazard where one deriver could silently drift from another
    (landing pass #5244, LAND-PAT-002). Consumers must use these properties
    instead of re-deriving a shard's names from ``job_key`` themselves.
    """

    job_key: str
    paths: tuple[str, ...]
    ignores: tuple[str, ...] = field(default_factory=tuple)
    suite_key: str = ""

    def resolved_suite_key(self) -> str:
        """The ``--suite-key`` literal this shard's escalation step must use.

        Defaults to ``job_key`` when ``suite_key`` is left empty, so a shard
        added to the roster without an explicit override still gets a
        distinct, non-colliding key (FR-011/FR-015) derived from its own
        job identity rather than silently falling back to a shared default.
        """
        return self.suite_key or self.job_key

    @property
    def shard_number(self) -> int:
        """The shard's numeric ordinal, parsed from ``job_key`` (the single
        SSOT parse -- every other derived name below is computed FROM this,
        never independently re-parsed from ``job_key`` a second way)."""
        match = _JOB_KEY_RE.fullmatch(self.job_key)
        if not match:
            raise ValueError(f"job_key {self.job_key!r} does not match the interpreter-matrix-shard-<N> shape ({_JOB_KEY_RE.pattern!r})")
        return int(match.group(1))

    @property
    def exit_var(self) -> str:
        """The ``$GITHUB_ENV`` exit-code variable this shard's suite,
        escalation, and fail-loud steps must all read/write in common."""
        return f"INTERPRETER_SHARD_{self.shard_number}_EXIT"

    @property
    def junit_filename(self) -> str:
        """The ``--junitxml`` filename (under ``out/reports/``) this shard's
        suite step must write."""
        return f"xunit-nightly-interpreter-3.13-shard-{self.shard_number}.xml"

    @property
    def artifact_name(self) -> str:
        """The ``actions/upload-artifact`` ``name:`` this shard's reports
        upload under."""
        return f"ci-nightly-interpreter-3.13-shard-{self.shard_number}-reports"

    @property
    def lane_label(self) -> str:
        """The short ``interpreter-<N>`` label used to key this shard's
        entry in exit-honesty's per-lane lookup tables (distinct from
        ``resolved_suite_key()``, which is the longer
        ``interpreter-3.13-shard-<N>`` literal passed to the escalation
        script)."""
        return f"interpreter-{self.shard_number}"


