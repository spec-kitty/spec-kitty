"""Red-first tests for the WP04 hard-cutover END-STATE (IC-06 / FR-012, FR-013, SC-003).

WP01's ``test_backfill_migration.py`` already proves the backfill WRITES ledger
records. This file asserts the CUTOVER end-state WP04 owns:

* a pre-ledger project's prior migrations are recognised and NOT re-run (G-2);
* ``metadata.yaml`` no longer persists ``migrations.applied`` -- the runner's
  transitional dual-write becomes a no-op at ``save()`` level (C-001 single
  authority, NFR-003 accepted back-compat cost);
* the stale on-disk ``migrations:`` block is retired once the ledger is the
  authority, and STAYS gone across a subsequent ``save()`` (R4 -- the
  merge-preserving save never re-adds it);
* a re-run makes no new records and no material metadata change (G-2 no-op).
"""

from __future__ import annotations

from pathlib import Path

from kernel.clock import now_utc

from specify_cli.upgrade.ledger import MigrationLedger
from specify_cli.upgrade.metadata import MigrationRecord, ProjectMetadata
from specify_cli.upgrade.migrations.m_4_0_0rc8_backfill_migration_ledger import (
    BackfillMigrationLedgerMigration,
)
from specify_cli.upgrade.registry import migration_settled

# A real, registered, tracked migration id that a pre-ledger project would have
# recorded in metadata.yaml before the ledger existed.
_PRIOR_ID = "3.1.1_charter_rename"

_PRE_LEDGER_METADATA = """# Spec Kitty Project Metadata
# Auto-generated by spec-kitty init/upgrade
# DO NOT EDIT MANUALLY

spec_kitty:
  version: 3.2.0
  initialized_at: '2026-01-01T00:00:00+00:00'
  last_upgraded_at: null
environment:
  python_version: ''
  platform: ''
  platform_version: ''
migrations:
  applied:
  - id: 3.1.1_charter_rename
    applied_at: '2026-01-01T00:00:00+00:00'
    result: success
    notes: null
"""


def _seed_pre_ledger_project(tmp_path: Path) -> Path:
    """A project with a metadata ``migrations:`` block on disk and NO ledger yet."""
    kittify = tmp_path / ".kittify"
    kittify.mkdir(parents=True, exist_ok=True)
    (kittify / "metadata.yaml").write_text(_PRE_LEDGER_METADATA, encoding="utf-8")
    return tmp_path


def test_pre_ledger_prior_migrations_recorded_and_not_rerun(tmp_path: Path) -> None:
    """The backfill adopts the prior applied migration so selection skips it (G-2)."""
    project = _seed_pre_ledger_project(tmp_path)
    migration = BackfillMigrationLedgerMigration()

    migration.apply(project)

    ledger = MigrationLedger(project)
    assert _PRIOR_ID in {r.id for r in ledger.read_tracked()}

    prior = next(r for r in ledger.read_tracked() if r.id == _PRIOR_ID)

    class _PriorStub:
        migration_id = _PRIOR_ID
        clone_local_effect = False

    # The prior migration is now settled by the ledger, so a selection pass skips it.
    assert migration_settled(ledger, _PriorStub()) is True
    assert prior.result == "success"


def test_applied_migrations_removed_as_authority_no_dual_write(tmp_path: Path) -> None:
    """After the cutover, ``save()`` no longer persists applied state (F2, no dual-write)."""
    kittify = tmp_path / ".kittify"
    kittify.mkdir(parents=True, exist_ok=True)
    metadata = ProjectMetadata(version="4.0.0rc8", initialized_at=now_utc())

    # The runner's transitional dual-write still calls record_migration + save.
    assert metadata.record_migration(_PRIOR_ID, "success") is True
    metadata.save(kittify)

    text = (kittify / "metadata.yaml").read_text(encoding="utf-8")
    assert "migrations:" not in text, "save() must not write a migrations block (no dual-write)"
    reloaded = ProjectMetadata.load(kittify)
    assert reloaded is not None
    assert reloaded.applied_migrations == [], "applied_migrations is retired as an on-disk authority"


def test_migrations_block_gone_and_stays_gone_across_save(tmp_path: Path) -> None:
    """Once the ledger is adopted, a stale on-disk ``migrations:`` block is retired for good (R4)."""
    project = _seed_pre_ledger_project(tmp_path)
    kittify = project / ".kittify"

    # Before the ledger exists, a save must PRESERVE the block (the backfill still
    # has to read it): the strip is gated on ledger adoption, never premature.
    ProjectMetadata.load(kittify).save(kittify)  # type: ignore[union-attr]
    assert "migrations:" in (kittify / "metadata.yaml").read_text(encoding="utf-8")

    # Adopt the ledger (the real backfill run).
    BackfillMigrationLedgerMigration().apply(project)

    # The next save retires the now-dead block...
    wrote = ProjectMetadata.load(kittify).save(kittify)  # type: ignore[union-attr]
    assert wrote is True
    assert "migrations:" not in (kittify / "metadata.yaml").read_text(encoding="utf-8")

    # ...and a subsequent save keeps it gone (the merge-preserving save never re-adds it).
    ProjectMetadata.load(kittify).save(kittify)  # type: ignore[union-attr]
    assert "migrations:" not in (kittify / "metadata.yaml").read_text(encoding="utf-8")


def test_version_schema_stamp_survives_block_strip(tmp_path: Path) -> None:
    """Retiring the applied block leaves the version/schema stamp untouched (NFR-003, F4)."""
    project = _seed_pre_ledger_project(tmp_path)
    kittify = project / ".kittify"
    BackfillMigrationLedgerMigration().apply(project)

    ProjectMetadata.load(kittify).save(kittify)  # type: ignore[union-attr]
    reloaded = ProjectMetadata.load(kittify)
    assert reloaded is not None
    assert reloaded.version == "3.2.0"


def test_rerun_no_op_control(tmp_path: Path) -> None:
    """A re-run after the cutover writes no new ledger record and no material metadata change (G-2)."""
    project = _seed_pre_ledger_project(tmp_path)
    kittify = project / ".kittify"
    migration = BackfillMigrationLedgerMigration()
    migration.apply(project)
    ProjectMetadata.load(kittify).save(kittify)  # type: ignore[union-attr]

    tracked_before = MigrationLedger(project).read_tracked()
    text_before = (kittify / "metadata.yaml").read_text(encoding="utf-8")

    # Re-run: nothing left to backfill, and a settled save is a no-op.
    assert migration.detect(project) is False
    migration.apply(project)
    wrote = ProjectMetadata.load(kittify).save(kittify)  # type: ignore[union-attr]

    assert wrote is False, "a settled save must not churn the file (G-2 no-op)"
    assert [r.id for r in MigrationLedger(project).read_tracked()] == [r.id for r in tracked_before]
    assert (kittify / "metadata.yaml").read_text(encoding="utf-8") == text_before


def test_prior_record_detect_true_before_backfill(tmp_path: Path) -> None:
    """Control: a pre-ledger project is detected as needing the backfill, not silently skipped."""
    project = _seed_pre_ledger_project(tmp_path)
    assert BackfillMigrationLedgerMigration().detect(project) is True


def test_metadata_only_backfill_adds_no_version_floor_records(tmp_path: Path) -> None:
    """The backfill seeds ONLY from metadata.applied_migrations -- no version-floor baseline (operator ruling)."""
    project = _seed_pre_ledger_project(tmp_path)
    BackfillMigrationLedgerMigration().apply(project)

    tracked_ids = {r.id for r in MigrationLedger(project).read_tracked()}
    # Exactly the one id the metadata recorded -- nothing floor-seeded from the manifest/version window.
    assert tracked_ids == {_PRIOR_ID}
    seed = MigrationRecord(id=_PRIOR_ID, applied_at=now_utc(), result="success")
    assert seed.id == _PRIOR_ID  # the only seed source is the recorded metadata row
