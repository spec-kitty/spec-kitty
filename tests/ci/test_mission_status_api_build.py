_FORBIDDEN_VERSION = re.compile(r"(\+|latest|\[|\]|\(|\)|,|\bSNAPSHOT\b|\brelease\b|\bintegration\b)", re.IGNORECASE)


def catalog_violations(catalog_text: str) -> list[str]:
    data = tomllib.loads(catalog_text)
    found: list[str] = []
    versions = data.get("versions", {})
    if not versions:
        found.append("the catalog declares no versions")
    for name, value in versions.items():
        if not isinstance(value, str) or not re.fullmatch(r"\d+(\.\d+)*", value) or _FORBIDDEN_VERSION.search(value):
            found.append(f"version {name} = {value!r} is not an exact version")
    for section in ("libraries", "plugins"):
        for name, entry in data.get(section, {}).items():
            if isinstance(entry, str):
                if entry.count(":") >= 2 and _FORBIDDEN_VERSION.search(entry.split(":")[-1]):
                    found.append(f"{section} {name} carries a dynamic version")
                continue
            version = entry.get("version")
            if isinstance(version, str):
                found.append(f"{section} {name} writes a literal version; use version.ref")
            elif isinstance(version, dict) and set(version) - {"ref"}:
                found.append(f"{section} {name} uses a version range or constraint")
    return found


