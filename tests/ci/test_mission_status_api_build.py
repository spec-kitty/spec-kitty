def pin_violations(text: str) -> list[str]:
    found: list[str] = []
    seen = 0
    for line in text.splitlines():
        match = USES_LINE.match(line)
        if not match or line.lstrip().startswith("#"):
            continue
        seen += 1
        reference, rest = match.group(1), match.group(2)
        if not SHA_PIN.match(reference):
            found.append(f"uses {reference} is not pinned to a 40-hex commit")
            continue
        action, sha = reference.split("@")
        expected = EXPECTED_PINS.get(action)
        if expected is None:
            found.append(f"uses {action} is not in the verified action table")
        elif sha != expected[0] or f"# {expected[1]}" not in rest:
            found.append(f"uses {action} is not the verified commit {expected[0]} with its {expected[1]} comment")
    if seen == 0:
        found.append("no uses: line parsed (vacuous)")
    return found


def wrapper_order_violations(text: str) -> list[str]:
    found: list[str] = []
    gradle_jobs = 0
    for name, job in _jobs(_wf(text)).items():
        steps = _steps(job)
        first_gradle = next((i for i, s in enumerate(steps) if "gradlew" in str(s.get("run", ""))), None)
        if first_gradle is None:
            continue
        gradle_jobs += 1
        validation = next((i for i, s in enumerate(steps) if str(s.get("uses", "")).startswith(WRAPPER_VALIDATION + "@")), None)
        if validation is None or validation > first_gradle:
            found.append(f"job {name}: {WRAPPER_VALIDATION} does not precede the first gradlew step")
    if gradle_jobs < 2:
        found.append("fewer than two jobs call gradlew (the jvm job and the native legs)")
    return found


