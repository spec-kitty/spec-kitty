# --- WP03: wrapper, catalog and literal versions (AC-14a, AC-14b, AC-14g) ---------------------------------------------------------


def wrapper_violations(properties_text: str, jar_bytes: bytes) -> list[str]:
    found: list[str] = []
    props = dict(line.split("=", 1) for line in properties_text.splitlines() if "=" in line and not line.lstrip().startswith("#"))
    if props.get("distributionSha256Sum") != GRADLE_DISTRIBUTION_SHA256:
        found.append("distributionSha256Sum is absent or not the recorded Gradle 9.7.1 distribution checksum")
    if f"gradle-{GRADLE_VERSION}-bin.zip" not in props.get("distributionUrl", ""):
        found.append(f"distributionUrl does not name gradle-{GRADLE_VERSION}-bin.zip")
    if not props.get("distributionUrl", "").startswith("https\\://services.gradle.org/"):
        found.append("distributionUrl is not the https services.gradle.org distribution")
    # File-integrity check of a binary wrapper jar, not a charter content hash.
    if hashlib.sha256(jar_bytes).hexdigest() != WRAPPER_JAR_SHA256:  # noqa: TID251
        found.append("gradle-wrapper.jar is not the recorded wrapper jar (one byte differs)")
    return found


