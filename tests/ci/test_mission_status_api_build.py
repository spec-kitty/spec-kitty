_RULE = re.compile(
    r'rule\s*\{(?:[^{}]*?element\s*=\s*"(?P<element>[A-Z]+)")?[^{}]*includes\s*=\s*listOf\("(?P<pattern>[^"]+)"\)[^{}]*limit\s*\{[^{}]*counter\s*=\s*"(?P<counter>[A-Z]+)"[^{}]*'
    r'minimum\s*=\s*"(?P<minimum>[0-9.]+)"\.toBigDecimal\(\)'
)
EXPECTED_RULES = [
    ("CLASS", "org.speckitty.missionstatus.domain.*", "LINE", "0.90"),
    ("CLASS", "org.speckitty.missionstatus.application.*", "LINE", "0.90"),
    ("CLASS", "org.speckitty.missionstatus.domain.*", "BRANCH", "0.80"),
]


def jacoco_violations(build_text: str) -> list[str]:
    found: list[str] = []
    body = _block(build_text, 'tasks.named<JacocoCoverageVerification>("jacocoTestCoverageVerification")')
    if body is None:
        return ["jacocoTestCoverageVerification is not configured"]
    rules = [(m["element"], m["pattern"], m["counter"], m["minimum"]) for m in _RULE.finditer(body)]
    if rules != EXPECTED_RULES:
        found.append(f"the verification rules are {rules}, expected {EXPECTED_RULES}")
    if body.count("rule {") != 3:
        found.append("jacocoTestCoverageVerification does not hold exactly three rules")
    check = _block(build_text, 'tasks.named("check")') or ""
    for dependency in ("jacocoTestCoverageVerification", "jacocoScopeCheck"):
        if f'"{dependency}"' not in check:
            found.append(f"check does not depend on {dependency}")
    scope = _block(build_text, 'tasks.register("jacocoScopeCheck")') or ""
    if "jacoco-class-floor.properties" not in build_text or not scope:
        found.append("jacocoScopeCheck is missing or does not read jacoco-class-floor.properties")
    if 'dependsOn("jacocoTestReport")' not in scope:
        found.append("jacocoScopeCheck does not run after jacocoTestReport")
    return found


