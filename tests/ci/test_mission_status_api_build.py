def _text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _code(path: Path) -> str:
    """The file text without full-line comments (``//`` in Kotlin, ``#`` in properties and TOML)."""
    return "\n".join(line for line in _text(path).splitlines() if not line.lstrip().startswith(("//", "#")))


def _block(text: str, header: str) -> str | None:
    """The brace-balanced body that follows the first occurrence of ``header`` (None when the header is absent)."""
    start = text.find(header)
    if start < 0:
        return None
    brace = text.find("{", start + len(header))
    if brace < 0:
        return None
    depth = 0
    for index in range(brace, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[brace + 1 : index]
    return None


