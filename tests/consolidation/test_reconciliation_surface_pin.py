"""Import-surface pin for ``specify_cli.consolidation.reconciliation`` (WP04 / FR-018).

Mission consolidation-window-provenance-01M6Y84D later splits the 4,096-line
``reconciliation.py`` into several modules behind a re-exporting facade. These
tests pin the facade's import surface so the split cannot silently drop or
re-bind a name that ``src/`` or ``tests/`` reaches:

1. ``test_every_pinned_name_is_importable`` — every pinned name is still an
   attribute of the facade.
2. ``test_pinned_names_keep_object_identity`` — every pinned name is the same
   object as at its home (its defining module for functions and classes, every
   binding family module for everything else).
3. ``test_scanned_surface_is_pinned`` — every name the codebase reaches on the
   facade today (found by :func:`scan_reconciliation_surface`, never by hand)
   is in the pinned JSON. Subset, not equality: later work packages retarget
   patches to new homes, which shrinks the scan, and that must stay green.
4. ``test_removed_name_fails_the_pin`` — the control proving the pin can fail.

Controls added in review cycle 1: ``test_identity_check_catches_family_drift``
(the identity check can fail), ``test_scanner_resolves_relative_imports``
(relative imports resolve against the importing file's package) and
``test_scanner_collects_every_patch_form`` (every patch spelling, including
bare-``patch`` ``patch.object``, reaches the scanner).

The pinned list lives in ``reconciliation_surface.json`` and is generated by
the scanner, never hand-edited: regenerate with
``SPEC_KITTY_REGEN_RECONCILIATION_SURFACE=1 uv run --frozen pytest -q
tests/consolidation/test_reconciliation_surface_pin.py::test_scanned_surface_is_pinned``.
"""

from __future__ import annotations

import ast
import inspect
import json
import os
import re
import sys
from collections.abc import Iterator, Mapping
from pathlib import Path
from types import ModuleType

import pytest
from specify_cli.consolidation import reconciliation
from tests.consolidation.reconciliation_family import RECONCILIATION_FAMILY, patch_callee_name

pytestmark = pytest.mark.fast

repo_root = Path(__file__).resolve().parents[2]
PIN_FILE = Path(__file__).resolve().parent / "reconciliation_surface.json"
REGEN_ENV = "SPEC_KITTY_REGEN_RECONCILIATION_SURFACE"

_FACADE_PACKAGE = "specify_cli.consolidation"
_FACADE = f"{_FACADE_PACKAGE}.reconciliation"
_FACADE_ATTRIBUTE_RE = re.compile(r"^specify_cli\.consolidation\.reconciliation\.([A-Za-z_][A-Za-z0-9_]*)$")
_PATCH_CALLEES = ("setattr", "patch", "patch.object")


def _is_family_source(repo: Path, path: Path) -> bool:
    """True for the facade (and future split modules) themselves, which the scan skips."""
    consolidation = repo / "src" / "specify_cli" / "consolidation"
    return path.parent == consolidation and path.name.startswith("reconciliation")


def _iter_python_files(repo: Path) -> Iterator[Path]:
    """Every ``*.py`` under ``src/`` and ``tests/`` except ``__pycache__`` and the family sources."""
    for base in (repo / "src", repo / "tests"):
        for path in sorted(base.rglob("*.py")):
            if "__pycache__" not in path.parts and not _is_family_source(repo, path):
                yield path


def _file_package(repo: Path, path: Path) -> str:
    """The dotted package containing *path* (the ``src/`` tree or the ``tests/`` tree)."""
    for base, prefix in ((repo / "src", ""), (repo / "tests", "tests")):
        try:
            relative = path.relative_to(base)
        except ValueError:
            continue
        parts = relative.parts[:-1]
        return ".".join((prefix, *parts) if prefix else parts)
    return ""


def _resolve_import_module(package: str, node: ast.ImportFrom) -> str | None:
    """The dotted module an ``ImportFrom`` resolves to inside *package*.

    Absolute imports (``level == 0``) resolve to ``node.module``. Relative
    imports (``level > 0``, e.g. ``from .reconciliation import X`` in
    ``src/specify_cli/consolidation/``) resolve against the importing file's
    package (review cycle 1: the scanner used to ignore ``level`` and miss
    every relative import, so names reached only that way escaped the pin).
    ``None`` when a bare ``from <dots> import name`` has no resolvable anchor.
    """
    if node.level == 0:
        return node.module
    parts = package.split(".") if package else []
    if node.level - 1 > len(parts):
        return None
    anchor = parts[: len(parts) - (node.level - 1)]
    if node.module:
        return ".".join((*anchor, node.module))
    return ".".join(anchor) if anchor else None


def _facade_aliases(tree: ast.AST, package: str) -> dict[str, str]:
    """Local names bound to the facade module, at any scope (e.g. ``rec``).

    Handles both ``from specify_cli.consolidation import reconciliation`` and
    the relative ``from . import reconciliation`` inside the package.
    """
    aliases: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            if _resolve_import_module(package, node) != _FACADE_PACKAGE:
                continue
            for alias in node.names:
                if alias.name == "reconciliation":
                    aliases[alias.asname or alias.name] = _FACADE
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name == _FACADE:
                    aliases[alias.asname or alias.name] = _FACADE
    return aliases


def _module_string_constants(tree: ast.Module) -> dict[str, str]:
    """Module-level ``NAME = "<string>"`` constants (f-string bases)."""
    consts: dict[str, str] = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        value = node.value
        if isinstance(target, ast.Name) and isinstance(value, ast.Constant) and isinstance(value.value, str):
            consts[target.id] = value.value
    return consts


def _names_from_imports(tree: ast.AST, package: str) -> set[str]:
    """Names imported from the facade by name (``from ...reconciliation import X``).

    Resolves relative imports (``from .reconciliation import X``) against
    *package*, so a same-package consumer is scanned the same as an absolute one.
    """
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and _resolve_import_module(package, node) == _FACADE:
            names.update(alias.name for alias in node.names)
    return names


def _names_from_attributes(tree: ast.AST, aliases: Mapping[str, str]) -> set[str]:
    """Names reached as attributes on a facade alias (``rec.<name>``, any context)."""
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name) and node.value.id in aliases:
            names.add(node.attr)
    return names


def _names_from_strings(tree: ast.AST) -> set[str]:
    """Names embedded in anchored facade strings (patch targets and friends)."""
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            match = _FACADE_ATTRIBUTE_RE.match(node.value)
            if match:
                names.add(match.group(1))
    return names


def _fstring_attribute(node: ast.JoinedStr, consts: Mapping[str, str]) -> str | None:
    """The name in a two-part f-string ``f"{BASE}.<name>"`` whose BASE is the facade."""
    if len(node.values) != 2:
        return None
    first, second = node.values
    if not (isinstance(first, ast.FormattedValue) and isinstance(first.value, ast.Name)):
        return None
    if not (isinstance(second, ast.Constant) and isinstance(second.value, str)):
        return None
    suffix = second.value
    if not (suffix.startswith(".") and suffix[1:].isidentifier()):
        return None
    return suffix[1:] if consts.get(first.value.id) == _FACADE else None


def _names_from_fstrings(tree: ast.AST, consts: Mapping[str, str]) -> set[str]:
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.JoinedStr):
            name = _fstring_attribute(node, consts)
            if name:
                names.add(name)
    return names


def _patched_name_from_call(node: ast.Call, aliases: Mapping[str, str]) -> str | None:
    """The name patched by a module-object call (``setattr(alias, "<name>", ...)``)."""
    callee = patch_callee_name(node.func)
    if callee not in _PATCH_CALLEES or len(node.args) < 2:
        return None
    first, second = node.args[0], node.args[1]
    if not (isinstance(first, ast.Name) and first.id in aliases):
        return None
    return second.value if isinstance(second, ast.Constant) and isinstance(second.value, str) else None


def _names_from_setattr_calls(tree: ast.AST, aliases: Mapping[str, str]) -> set[str]:
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            name = _patched_name_from_call(node, aliases)
            if name:
                names.add(name)
    return names


def _names_reached_in_source(source: str, package: str) -> set[str]:
    """Every facade name one source file reaches, given its *package*.

    Split out of :func:`scan_reconciliation_surface` so the control tests can
    run the exact scanner over synthetic sources (the corpus scan must never be
    the only exerciser of these paths — a bug that only misfires on synthetic
    code would otherwise hide until real code hits it).
    """
    tree = ast.parse(source)
    aliases = _facade_aliases(tree, package)
    consts = _module_string_constants(tree)
    names: set[str] = set()
    names |= _names_from_imports(tree, package)
    names |= _names_from_attributes(tree, aliases)
    names |= _names_from_strings(tree)
    names |= _names_from_fstrings(tree, consts)
    names |= _names_from_setattr_calls(tree, aliases)
    return names


def scan_reconciliation_surface(repo: Path) -> set[str]:
    """Every name that ``src/`` and ``tests/`` reach on the reconciliation facade.

    Generated, never hand-curated (IC-04): the name list must come from code so
    a missed patch form cannot silently shrink the pin. Parse failures raise
    rather than skip — a silently skipped file is a silently shrunk surface.
    """
    names: set[str] = set()
    for path in _iter_python_files(repo):
        names |= _names_reached_in_source(path.read_text(encoding="utf-8"), _file_package(repo, path))
    return names


def _load_pinned_names() -> list[str]:
    data = json.loads(PIN_FILE.read_text(encoding="utf-8"))
    assert isinstance(data, list)
    names = [name for name in data if isinstance(name, str)]
    assert len(names) == len(data), "reconciliation_surface.json holds a non-string entry"
    return names


def _assert_pinned_names_importable(module: ModuleType, names: list[str]) -> None:
    missing = [name for name in names if not hasattr(module, name)]
    assert not missing, f"names missing from {module.__name__}: {sorted(missing)}"


def test_every_pinned_name_is_importable() -> None:
    _assert_pinned_names_importable(reconciliation, _load_pinned_names())


def _assert_pinned_names_keep_identity(module: ModuleType, names: list[str], family: tuple[ModuleType, ...]) -> None:
    """Every pinned *name* on *module* is the same object its home(s) bind.

    Split out of the test so the drift control can run the exact assertion
    against a synthetic family (a control that cannot fail proves nothing).
    ``__all__`` alone is exempt from the family-wide branch (orchestrator
    ruling 2026-11-09, WP10): it is pinned only because the scanner reads the
    facade's ``__all__`` in this file's regen branch, and every split module's
    own ``__all__`` is a per-module dunder, not a drift of the facade's export
    surface. It stays pinned and importable; every other rebound binding still
    fails.
    """
    for name in names:
        obj = getattr(module, name)
        if inspect.isfunction(obj) or inspect.isclass(obj):
            home = sys.modules[obj.__module__]
            assert getattr(home, obj.__name__) is obj, f"{name} is not the object its home binds"
        elif name != "__all__":
            for member in family:
                if name in vars(member):
                    assert vars(member)[name] is obj, f"{name} drifted across the reconciliation family"


def test_pinned_names_keep_object_identity() -> None:
    _assert_pinned_names_keep_identity(reconciliation, _load_pinned_names(), RECONCILIATION_FAMILY)


def test_identity_check_catches_family_drift() -> None:
    """Control: the identity check fails when a family member rebinds a name."""
    names = _load_pinned_names()
    drifted = next(name for name in names if not (inspect.isfunction(getattr(reconciliation, name)) or inspect.isclass(getattr(reconciliation, name))))
    fake_member = ModuleType("reconciliation_fake_member")
    setattr(fake_member, drifted, object())  # a different object than the facade binds
    with pytest.raises(AssertionError, match=f"{drifted} drifted"):
        _assert_pinned_names_keep_identity(reconciliation, names, (fake_member,))


def test_identity_check_skips_only_dunder_all() -> None:
    """Control (orchestrator ruling 2026-11-09, WP10): the family identity check skips ``__all__`` alone.

    Each split module declares its own ``__all__`` (WP10 R6 / C-007), which is a
    per-module dunder, not a drift of the facade's export surface. A rebound
    binding of any other pinned name must still fail, and a family member whose
    only rebinding is ``__all__`` must not.
    """
    names = _load_pinned_names()
    non_dunder = next(
        name for name in names if name != "__all__" and not (inspect.isfunction(getattr(reconciliation, name)) or inspect.isclass(getattr(reconciliation, name)))
    )
    fake_drifted = ModuleType("reconciliation_fake_non_all_drift")
    setattr(fake_drifted, non_dunder, object())  # a different object than the facade binds
    with pytest.raises(AssertionError, match=f"{non_dunder} drifted"):
        _assert_pinned_names_keep_identity(reconciliation, names, (fake_drifted,))

    fake_all_only = ModuleType("reconciliation_fake_all_only")
    vars(fake_all_only)["__all__"] = ["a", "different", "list"]
    _assert_pinned_names_keep_identity(reconciliation, names, (fake_all_only,))


@pytest.mark.non_sandbox
def test_scanned_surface_is_pinned() -> None:
    scanned = scan_reconciliation_surface(repo_root)
    if os.environ.get(REGEN_ENV) == "1":
        names = sorted(scanned | set(reconciliation.__all__))
        PIN_FILE.write_text(json.dumps(names, indent=2) + "\n", encoding="utf-8")
        return
    unpinned = scanned - set(_load_pinned_names())
    assert not unpinned, (
        f"names reached on the facade but not pinned: {sorted(unpinned)}; "
        f"regenerate with {REGEN_ENV}=1 uv run --frozen pytest -q "
        "tests/consolidation/test_reconciliation_surface_pin.py::test_scanned_surface_is_pinned"
    )


def test_removed_name_fails_the_pin(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delattr(reconciliation, "build_approved_wp_set")
    with pytest.raises(AssertionError, match="build_approved_wp_set"):
        _assert_pinned_names_importable(reconciliation, _load_pinned_names())


def test_scanner_resolves_relative_imports() -> None:
    """Control: a relative import resolves against the importing file's package.

    Review cycle 1: the scanner ignored ``ImportFrom.level`` and missed every
    name reached only through ``from .reconciliation import X`` (the shape
    ``approved_attestation.py`` uses), so those names escaped the pin.
    """
    from_facade = _names_reached_in_source(
        "from .reconciliation import X, Y as Z\n",
        _FACADE_PACKAGE,
    )
    assert from_facade == {"X", "Y"}
    via_alias = _names_reached_in_source(
        "from . import reconciliation as rec\nprint(rec.Y)\n",
        _FACADE_PACKAGE,
    )
    assert via_alias == {"Y"}
    # The same relative text in another package resolves elsewhere: not the facade.
    elsewhere = _names_reached_in_source(
        "from .reconciliation import X\n",
        "tests.consolidation",
    )
    assert elsewhere == set()


def test_scanner_collects_every_patch_form() -> None:
    """Control: every patch spelling the corpus may use reaches the scanner.

    Review cycle 1: ``patch.object(...)`` where ``patch`` is a bare name (from
    ``from unittest.mock import patch``) was not recognized as a patch call.
    """
    source = (
        "from specify_cli.consolidation import reconciliation as rec\n"
        "from unittest import mock\n"
        "from unittest.mock import patch\n"
        "import unittest\n"
        'mock.patch("specify_cli.consolidation.reconciliation.Y")\n'
        'mock.patch.object(rec, "Y")\n'
        'unittest.mock.patch("specify_cli.consolidation.reconciliation.Y")\n'
        'unittest.mock.patch.object(rec, "Y")\n'
        'patch("specify_cli.consolidation.reconciliation.Y")\n'
        'patch.object(rec, "Y")\n'
    )
    assert _names_reached_in_source(source, "some.other.package") == {"Y"}
