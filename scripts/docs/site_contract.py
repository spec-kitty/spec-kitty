"""Project the doc-kitty contract onto the docsite (#6930; ADR 2026-10-31-1 D-1, D-8).

``scripts/docs/_dockitty_contract.py`` is the single authority for which ``docs/``
folders the site leaves out, which basenames are section indexes and the version
stance ``llms.txt`` carries (D-9, #6934). The site is JavaScript and cannot import it,
so this module writes those values to ``site/dockitty-contract.json`` and checks that the committed copy
still equals them. The copy is generated, never hand-edited.

Usage::

    python -m scripts.docs.site_contract           # (re)write site/dockitty-contract.json
    python -m scripts.docs.site_contract --check   # exit 1 when the copy has drifted
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Final

# Runnable bare (`python3 scripts/docs/site_contract.py`): resolve `scripts.*` from the script, not the cwd.
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from scripts.docs._dockitty_contract import EXCLUDED_FOLDERS, INDEX_BASENAMES, LLMS_STANCE  # noqa: E402

__all__ = ["CONTRACT_PATH", "check", "main", "render", "write"]

CONTRACT_PATH: Final[Path] = Path(__file__).resolve().parents[2] / "site" / "dockitty-contract.json"

_COMMENT: Final[str] = "GENERATED by `python -m scripts.docs.site_contract` from scripts/docs/_dockitty_contract.py; do not edit."


def _expected() -> dict[str, object]:
    return {
        "$comment": _COMMENT,
        "exclude": list(EXCLUDED_FOLDERS),
        "indexBasename": list(INDEX_BASENAMES),
        "llmsStance": LLMS_STANCE,
    }


def render() -> str:
    """The exact text of the generated contract copy."""
    return json.dumps(_expected(), indent=2) + "\n"


def write(path: Path = CONTRACT_PATH) -> None:
    """Write the contract copy to *path*."""
    path.write_text(render(), encoding="utf-8")


def check(path: Path = CONTRACT_PATH) -> list[str]:
    """Return the differences between the copy at *path* and the authority (empty when equal)."""
    try:
        actual = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return [f"{path} is missing; run `python -m scripts.docs.site_contract`"]
    except json.JSONDecodeError as error:
        return [f"{path} is not valid JSON: {error}"]
    if not isinstance(actual, dict):
        return [f"{path} must hold a JSON object"]
    expected = _expected()
    problems = [f"{key}: expected {value!r}, found {actual.get(key)!r}" for key, value in expected.items() if actual.get(key) != value]
    problems.extend(f"{key}: unexpected key" for key in sorted(set(actual) - set(expected)))
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="verify the committed copy instead of writing it")
    parser.add_argument("--path", type=Path, default=CONTRACT_PATH, help="the contract copy (default: site/dockitty-contract.json)")
    args = parser.parse_args(argv)
    if not args.check:
        write(args.path)
        return 0
    problems = check(args.path)
    for problem in problems:
        print(f"site contract drift: {problem}", file=sys.stderr)
    if problems:
        print("Fix: python -m scripts.docs.site_contract", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
